document.addEventListener('DOMContentLoaded', () => {
  // 1. Voeg taalwisselaar (NL | EN | DE | ES) toe aan de header
  const headerCta = document.querySelector('.header-cta');
  const langSwitcher = document.createElement('div');
  langSwitcher.className = 'lang-switcher';
  langSwitcher.setAttribute('aria-label', 'Taal kiezen / Choose language / Sprache wählen / Elegir idioma');
  langSwitcher.innerHTML = `
    <button type="button" class="lang-btn active" data-lang="nl" title="Nederlands">🇳🇱 NL</button>
    <button type="button" class="lang-btn" data-lang="en" title="English">🇬🇧 EN</button>
    <button type="button" class="lang-btn" data-lang="de" title="Deutsch">🇩🇪 DE</button>
    <button type="button" class="lang-btn" data-lang="es" title="Español">🇪🇸 ES</button>
  `;

  if (headerCta) {
    headerCta.insertBefore(langSwitcher, headerCta.firstChild);
  }

  // Bepaal huidige pagina
  const pathParts = window.location.pathname.split('/');
  const currentPage = pathParts[pathParts.length - 1] || 'index.html';

  // Verzamel alle selectors en sla de originele Nederlandse HTML op
  const originalNL = {};
  const allSelectors = new Set([
    ...Object.keys(translations.en),
    ...Object.keys(pageTranslations[currentPage]?.en || {}),
  ]);

  allSelectors.forEach((selector) => {
    const el = document.querySelector(selector);
    if (el) {
      originalNL[selector] = el.innerHTML;
    }
  });

  function setLanguage(lang) {
    document.documentElement.lang = lang;
    localStorage.setItem('janPouwLang', lang);

    document.querySelectorAll('.lang-btn').forEach((btn) => {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    allSelectors.forEach((selector) => {
      const el = document.querySelector(selector);
      if (!el) return;

      if (lang === 'nl') {
        if (originalNL[selector] !== undefined) {
          el.innerHTML = originalNL[selector];
        }
      } else {
        const pageMap = pageTranslations[currentPage]?.[lang] || {};
        const globalMap = translations[lang] || {};
        const translated = pageMap[selector] || globalMap[selector];
        if (translated) {
          el.innerHTML = translated;
        }
      }
    });
  }

  // Herstel laatst gekozen taal (standaard 'nl')
  const savedLang = localStorage.getItem('janPouwLang') || 'nl';
  if (savedLang !== 'nl') {
    setLanguage(savedLang);
  }

  langSwitcher.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.addEventListener('click', () => {
      setLanguage(btn.getAttribute('data-lang'));
    });
  });

  // 2. Mobiel menu openen / sluiten
  const mobileToggle = document.querySelector('.mobile-toggle');
  const navLinks = document.querySelector('.nav-links');

  if (mobileToggle && navLinks) {
    mobileToggle.addEventListener('click', () => {
      const isOpen = navLinks.classList.toggle('open');
      mobileToggle.setAttribute('aria-expanded', isOpen);
    });
  }

  // 3. Portfolio filter op Over Jan & Projecten pagina
  const filterButtons = document.querySelectorAll('.filter-btn');
  const galleryItems = document.querySelectorAll('.gallery-item');

  if (filterButtons.length > 0 && galleryItems.length > 0) {
    filterButtons.forEach((btn) => {
      btn.addEventListener('click', () => {
        filterButtons.forEach((b) => b.classList.remove('active'));
        btn.classList.add('active');

        const filter = btn.getAttribute('data-filter');
        galleryItems.forEach((item) => {
          const category = item.getAttribute('data-category');
          if (filter === 'all' || category === filter) {
            item.classList.remove('hidden');
          } else {
            item.classList.add('hidden');
          }
        });
      });
    });
  }

  // 4. URL-parameter uitlezen op Contactpagina
  const urlParams = new URLSearchParams(window.location.search);
  const preselectedType = urlParams.get('onderwerp');
  const typeSelect = document.getElementById('klus-type');
  const locationSelect = document.getElementById('locatie');

  if (preselectedType && typeSelect) {
    for (const option of typeSelect.options) {
      if (option.value === preselectedType) {
        option.selected = true;
      }
    }
  }
  if (preselectedType === 'spanje' && locationSelect) {
    locationSelect.value = 'Spanje (Costa Blanca / Costa del Sol)';
  }

  // 5. Offerteformulier afhandeling (meertalig)
  const contactForm = document.getElementById('offerte-form');
  const successBox = document.getElementById('form-success');

  if (contactForm && successBox) {
    contactForm.addEventListener('submit', (e) => {
      e.preventDefault();
      const lang = localStorage.getItem('janPouwLang') || 'nl';
      const naam = document.getElementById('naam')?.value || '';

      if (lang === 'en') {
        successBox.innerHTML = `Thank you <strong>${naam}</strong>! I have received your message and will contact you personally within 24 hours. — <em>Jan Pouw</em>`;
      } else if (lang === 'de') {
        successBox.innerHTML = `Vielen Dank <strong>${naam}</strong>! Ich habe Ihre Nachricht erhalten und melde mich innerhalb von 24 Stunden persönlich bei Ihnen. — <em>Jan Pouw</em>`;
      } else if (lang === 'es') {
        successBox.innerHTML = `¡Muchas gracias <strong>${naam}</strong>! He recibido tu mensaje y me pondré en contacto contigo personalmente en menos de 24 horas. — <em>Jan Pouw</em>`;
      } else {
        successBox.innerHTML = `Bedankt <strong>${naam}</strong>! Ik heb je bericht goed ontvangen en neem binnen 24 uur persoonlijk contact met je op. — <em>Jan Pouw</em>`;
      }

      successBox.style.display = 'block';
      contactForm.reset();
      successBox.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
    });
  }
});
